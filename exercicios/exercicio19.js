// A diferença principal é que o 'let' permite que o valor da variável seja alterado (reatribuído) ao longo do código, enquanto o 'const' cria uma constante cujo valor é fixo e não pode ser mudado após a declaração.
// Situação para 'let': A pontuação de um jogador em um jogo, que muda conforme ele ganha pontos.
// Situação para 'const': O valor de PI (3.14159) ou a URL base de uma API, que nunca devem mudar.
